# -*- coding:utf-8 -*-
"""
Loss-Objective Comparison Table Generator (code_new/make_loss_comparison_table.py)
==================================================================================
Computes 5-fold mean ± std for Linear+CE, Linear+Focal, ArcFace+CE, ArcFace+Focal,
and CosFace+Focal (plus SphereFace/DirectMargin if available) on Davis and KIBA,
and writes `Loss_Comparison_Table.tex`.
"""

import shutil
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
)

ROOT = Path("result")
OUT_DIR = Path("sci_plots_ablation")
OUT_DIR.mkdir(exist_ok=True)
PAPER_ABL_DIR = Path(__file__).resolve().parents[1] / "paper_new" / "sci_plots_ablation"

DATASETS = ["Davis", "KIBA"]
LOSS_VARIANTS = [
    ("ce", "CE", "Linear", "CE"),
    ("no_arcface", "Focal", "Linear", "Focal"),
    ("no_focalloss", "ArcFace+CE", "ArcFace", "CE"),
    ("full", "ArcFace+Focal", "ArcFace", "Focal"),
    ("cosface", "CosFace+Focal", "CosFace", "Focal"),
]
METRICS = ["AUC", "AUPR", "ACC", "F1", "MCC", "Pre", "Sn", "Sp"]


def sync_file(filepath):
    if PAPER_ABL_DIR.parent.exists() and Path(filepath).exists():
        PAPER_ABL_DIR.mkdir(parents=True, exist_ok=True)
        shutil.copy2(filepath, PAPER_ABL_DIR / Path(filepath).name)


def compute_metrics(y_true, y_score):
    y_pred = (y_score >= 0.5).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {
        "AUC": roc_auc_score(y_true, y_score),
        "AUPR": average_precision_score(y_true, y_score),
        "ACC": accuracy_score(y_true, y_pred),
        "F1": f1_score(y_true, y_pred, zero_division=0),
        "MCC": matthews_corrcoef(y_true, y_pred),
        "Pre": precision_score(y_true, y_pred, zero_division=0),
        "Sn": recall_score(y_true, y_pred, zero_division=0),
        "Sp": tn / (tn + fp) if (tn + fp) else 0.0,
    }


def load_fold_metrics(dataset, variant):
    rows = []
    for fold in range(1, 6):
        candidates = [
            ROOT / f"Ablation_{dataset}_Seed42" / variant / f"fold_{fold}" / "ROC_PRC_data.npz",
        ]
        if variant == "full":
            candidates.insert(0, ROOT / f"{dataset}_CV_Seed42" / f"fold_{fold}" / "ROC_PRC_data.npz")
        found = next((p for p in candidates if p.exists()), None)
        if found is None:
            continue
        data = np.load(found)
        row = compute_metrics(data["y_true"], data["y_scores"])
        row.update({"Dataset": dataset, "Variant": variant, "Fold": fold})
        rows.append(row)
    return rows


def fmt_mean_std(mean, std, n, bold=False):
    if not np.isfinite(mean):
        return "--"
    if n == 1 or not np.isfinite(std):
        text = f"{mean:.4f}*"
    else:
        text = f"{mean:.4f} $\\pm$ {std:.4f}"
    return f"\\textbf{{{text}}}" if bold else text


def build_summary():
    fold_rows, summary_rows = [], []

    for dataset in DATASETS:
        for variant, label, margin, loss in LOSS_VARIANTS:
            rows = load_fold_metrics(dataset, variant)
            fold_rows.extend(rows)

            summary = {
                "Dataset": dataset,
                "Variant": variant,
                "Loss setting": label,
                "Margin head": margin,
                "Training loss": loss,
                "n": len(rows),
                "Status": "available" if rows else "missing",
            }
            for metric in METRICS:
                values = np.array([r[metric] for r in rows], dtype=float)
                values = values[np.isfinite(values)]
                summary[f"{metric}_mean"] = values.mean() if values.size else np.nan
                summary[f"{metric}_std"] = values.std(ddof=1) if values.size > 1 else np.nan
            summary_rows.append(summary)

    if not fold_rows:
        print("[SKIP] No loss comparison NPZ files found locally; preserving existing Loss_Comparison_Table.tex.")
        return pd.DataFrame()

    fold_df = pd.DataFrame(fold_rows)
    summary_df = pd.DataFrame(summary_rows)

    f_path = OUT_DIR / "Loss_Comparison_Fold_Metrics.csv"
    s_path = OUT_DIR / "Loss_Comparison_Summary.csv"
    fold_df.to_csv(f_path, index=False)
    summary_df.to_csv(s_path, index=False)
    sync_file(f_path)
    sync_file(s_path)
    write_latex(summary_df)
    return summary_df


def write_latex(summary_df):
    lines = [
        "% Auto-generated by make_loss_comparison_table.py",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Loss-objective and margin-head control comparison on Davis and KIBA. All entries are reported as mean $\\pm$ standard deviation over five folds.}",
        "\\label{tab:loss_comparison}",
        "\\resizebox{\\textwidth}{!}{",
        "\\begin{tabular}{lllccccc}",
        "\\toprule",
        "\\textbf{Dataset} & \\textbf{Setting} & \\textbf{Head} & \\textbf{Loss} & \\textbf{n} & \\textbf{AUC} & \\textbf{F1} & \\textbf{MCC} \\\\",
        "\\midrule",
    ]
    for dataset in DATASETS:
        sub = summary_df[summary_df["Dataset"] == dataset]
        best = {metric: sub[f"{metric}_mean"].max() for metric in ["AUC", "F1", "MCC"]}
        for _, row in sub.iterrows():
            lines.append(
                f"{dataset} & {row['Loss setting']} & {row['Margin head']} & {row['Training loss']} & "
                f"{int(row['n'])} & {fmt_mean_std(row['AUC_mean'], row['AUC_std'], row['n'], np.isclose(row['AUC_mean'], best['AUC']))} & "
                f"{fmt_mean_std(row['F1_mean'], row['F1_std'], row['n'], np.isclose(row['F1_mean'], best['F1']))} & "
                f"{fmt_mean_std(row['MCC_mean'], row['MCC_std'], row['n'], np.isclose(row['MCC_mean'], best['MCC']))} \\\\"
            )
        if dataset != DATASETS[-1]:
            lines.append("\\midrule")
    lines.extend(["\\bottomrule", "\\end{tabular}", "}", "\\end{table}"])
    tex_path = OUT_DIR / "Loss_Comparison_Table.tex"
    tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sync_file(tex_path)


if __name__ == "__main__":
    df = build_summary()
    if not df.empty:
        print(df[["Dataset", "Loss setting", "n", "Status", "AUC_mean", "F1_mean", "MCC_mean"]].to_string(index=False))

