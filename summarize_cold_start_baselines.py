# -*- coding:utf-8 -*-
"""
Cold-Start Evaluation Summary, LaTeX Table & Publication Figure Builder
(code_new/summarize_cold_start_baselines.py)
================================================================================================
Aggregates Cold-Drug and Cold-Target 5-fold cross-validation results across all 5 datasets
(`Davis`, `KIBA`, `Enzyme`, `GPCRs`, `ion_channel`) and all 5 models (`DeepDTA`, `MPNN`,
`MolTrans`, `DrugBAN`, `ArcMDTI`), reading directly from `result/` CSVs (with log fallback).
Generates:
  - `Cold_Start_Baseline_Summary.csv`
  - `Cold_Start_Table.tex`
  - `Cold_Start_Comparison.pdf` / `Cold_Start_Comparison.png`
"""

import re
import shutil
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

DATASETS = ["Davis", "KIBA", "DrugBank", "Enzyme", "GPCRs", "ion_channel"]
DATASET_LABELS = {
    "Davis": "Davis",
    "KIBA": "KIBA",
    "DrugBank": "DrugBank",
    "Enzyme": "Enzyme",
    "GPCRs": "GPCRs",
    "ion_channel": "Ion Channel",
}
SCENARIOS = ["cold_drug", "cold_target"]
MODELS = ["DeepDTA", "MPNN", "MolTrans", "DrugBAN", "ArcMDTI"]
OUT_DIR = Path("sci_plots_comparison")
OUT_DIR.mkdir(exist_ok=True)
PAPER_DIR = Path(__file__).resolve().parents[1] / "paper_new"
PAPER_COMP_DIR = PAPER_DIR / "sci_plots_comparison"
PAPER_FIG_DIR = PAPER_DIR / "figures"


def sync_file(filepath):
    src = Path(filepath)
    if not src.exists():
        return
    if PAPER_DIR.exists():
        for dst_dir in (PAPER_COMP_DIR, PAPER_FIG_DIR):
            dst_dir.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst_dir / src.name)


def resolve_result_roots():
    base = Path(__file__).resolve().parent
    candidates = [
        Path("result"),
        base / "result",
        base.parent / "ArcMDTI_Server_Results" / "result",
        base / "ArcMDTI_Server_Results" / "result",
    ]
    roots = []
    for c in candidates:
        if c.exists() and c not in roots:
            roots.append(c)
    return roots or [Path("result")]


def load_from_result_dir(dataset, scenario, model):
    scen_up = scenario.upper()
    for root in resolve_result_roots():
        if model == "ArcMDTI":
            fold_csv = root / f"{dataset}_{scen_up}_CV_Seed42" / f"{dataset}_per_fold_metrics.csv"
        else:
            fold_csv = root / f"Baseline_{model}_{dataset}_{scen_up}" / "Detailed_Fold_Results.csv"

        if not fold_csv.exists():
            continue

        df = pd.read_csv(fold_csv)
        if "AUPR" not in df.columns and "AUPRC" in df.columns:
            df = df.rename(columns={"AUPRC": "AUPR"})
        if "ACC" not in df.columns and "Acc" in df.columns:
            df = df.rename(columns={"Acc": "ACC"})
        df = df.loc[:, ~df.columns.duplicated()]

        res = {}
        for m in ["AUC", "AUPR", "ACC", "F1", "MCC", "Pre", "Sn", "Sp"]:
            if m in df.columns:
                res[m] = float(df[m].mean())
                res[f"{m}_std"] = float(df[m].std()) if len(df) > 1 else 0.0
        if "AUC" in res:
            return res
    return None


def parse_mean_std(text, metric):
    patterns = [
        rf"^{metric}\s*:\s*([+-]?[0-9.]+)\s*(?:±|卤|\+/-)\s*([0-9.]+)",
        rf"^{metric}\s+([+-]?[0-9.]+)\s*$",
    ]
    for pattern in patterns:
        matches = re.findall(pattern, text, flags=re.MULTILINE)
        if matches:
            last = matches[-1]
            if isinstance(last, tuple):
                return float(last[0]), float(last[1])
            return float(last), 0.0
    return None, None


def parse_log(path):
    text = path.read_text(encoding="utf-8", errors="ignore")
    if "Return code: 0" not in text:
        return None
    auc, auc_std = parse_mean_std(text, "AUC")
    aupr, aupr_std = parse_mean_std(text, "AUPR")
    if aupr is None:
        aupr, aupr_std = parse_mean_std(text, "AUPRC")
    f1, f1_std = parse_mean_std(text, "F1")
    mcc, mcc_std = parse_mean_std(text, "MCC")
    if auc is None or f1 is None or mcc is None:
        return None
    return {
        "AUC": auc,
        "AUC_std": auc_std,
        "AUPR": aupr if aupr is not None else np.nan,
        "AUPR_std": aupr_std if aupr_std is not None else np.nan,
        "F1": f1,
        "F1_std": f1_std,
        "MCC": mcc if mcc is not None else np.nan,
        "MCC_std": mcc_std if mcc_std is not None else np.nan,
    }


def write_cold_start_latex(df):
    if df.empty:
        return
    metrics = ["AUC", "AUPR", "F1", "MCC"]
    lines = [
        "% Auto-generated by summarize_cold_start_baselines.py",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Out-of-distribution generalization performance under strict Cold-Drug ($\\mathcal{D}_{train} \\cap \\mathcal{D}_{test} = \\emptyset$) and Cold-Target ($\\mathcal{T}_{train} \\cap \\mathcal{T}_{test} = \\emptyset$) 5-fold cross-validation protocols across all six benchmark datasets (reported as Mean $\\pm$ Std). The best result for each dataset and metric is highlighted in \\textbf{bold}.}",
        "\\label{tab:cold_start}",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{llcccccccc}",
        "\\toprule",
        "\\multirow{2}{*}{\\textbf{Dataset}} & \\multirow{2}{*}{\\textbf{Model}} & \\multicolumn{4}{c}{\\textbf{Cold-Drug Setting ($\\mathcal{D}_{train} \\cap \\mathcal{D}_{test} = \\emptyset$)}} & \\multicolumn{4}{c}{\\textbf{Cold-Target Setting ($\\mathcal{T}_{train} \\cap \\mathcal{T}_{test} = \\emptyset$)}} \\\\",
        "\\cmidrule(lr){3-6} \\cmidrule(lr){7-10}",
        " & & \\textbf{AUC} & \\textbf{AUPR} & \\textbf{F1} & \\textbf{MCC} & \\textbf{AUC} & \\textbf{AUPR} & \\textbf{F1} & \\textbf{MCC} \\\\",
        "\\midrule",
    ]

    for ds in DATASETS:
        sub_ds = df[df["Dataset"] == ds]
        if sub_ds.empty:
            continue
        ds_label = DATASET_LABELS.get(ds, ds)
        sub_drug = sub_ds[sub_ds["Scenario"] == "cold-drug"].set_index("Model")
        sub_targ = sub_ds[sub_ds["Scenario"] == "cold-target"].set_index("Model")

        best_drug = {m: sub_drug[m].max() if m in sub_drug and not sub_drug.empty else np.nan for m in metrics}
        best_targ = {m: sub_targ[m].max() if m in sub_targ and not sub_targ.empty else np.nan for m in metrics}

        avail_models = [m for m in MODELS if m in sub_drug.index or m in sub_targ.index]
        for idx, model in enumerate(avail_models):
            ds_col = f"\\multirow{{{len(avail_models)}}}{{*}}{{\\textbf{{{ds_label}}}}}" if idx == 0 else ""
            m_name = "\\textbf{ArcMDTI (Ours)}" if model == "ArcMDTI" else model

            def fmt_cell(sub_table, best_dict, col):
                if model not in sub_table.index:
                    return "--"
                row = sub_table.loc[model]
                val = row.get(col, np.nan)
                std = row.get(f"{col}_std", np.nan)
                if not np.isfinite(val):
                    return "--"
                val_str = f"$-${abs(val):.4f}" if val < 0 else f"{val:.4f}"
                s = f"{val_str} $\\pm$ {std:.4f}" if np.isfinite(std) and std > 0 else val_str
                is_best = np.isfinite(best_dict[col]) and np.isclose(round(val, 4), round(best_dict[col], 4))
                return f"\\textbf{{{s}}}" if is_best else s

            drug_cells = " & ".join(fmt_cell(sub_drug, best_drug, m) for m in metrics)
            targ_cells = " & ".join(fmt_cell(sub_targ, best_targ, m) for m in metrics)
            lines.append(f"{ds_col} & {m_name} & {drug_cells} & {targ_cells} \\\\")
        lines.append("\\midrule")

    if lines[-1] == "\\midrule":
        lines[-1] = "\\bottomrule"
    else:
        lines.append("\\bottomrule")
    lines.extend(["\\end{tabular}%", "}", "\\end{table*}"])
    tex_path = OUT_DIR / "Cold_Start_Table.tex"
    tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sync_file(tex_path)


def plot_cold_start_comparison(df):
    if df.empty:
        return
    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.sans-serif": ["DejaVu Sans", "Arial", "Helvetica"],
        "axes.edgecolor": "#333333",
        "axes.linewidth": 0.9,
    })

    fig, axes = plt.subplots(1, 2, figsize=(14.8, 4.7), dpi=300)
    palette = {
        "DeepDTA": "#8EB4FA",
        "MPNN": "#8CE0C4",
        "MolTrans": "#F7D26A",
        "DrugBAN": "#B99CE3",
        "ArcMDTI": "#F08A7D",
    }
    display_names = {
        "DeepDTA": "DeepDTA",
        "MPNN": "MPNN",
        "MolTrans": "MolTrans",
        "DrugBAN": "DrugBAN",
        "ArcMDTI": "ArcMDTI (Ours)",
    }

    # Keep consistent dataset order across both panels (all 6 datasets)
    ds_order = ["Davis", "KIBA", "DrugBank", "Enzyme", "GPCRs", "ion_channel"]
    x = np.arange(len(ds_order))
    width = 0.15

    for ax_idx, (scen, title) in enumerate([
        ("cold-drug", "(a) Cold-Drug 5-Fold CV ($\\mathcal{D}_{train} \\cap \\mathcal{D}_{test} = \\emptyset$)"),
        ("cold-target", "(b) Cold-Target 5-Fold CV ($\\mathcal{T}_{train} \\cap \\mathcal{T}_{test} = \\emptyset$)"),
    ]):
        ax = axes[ax_idx]
        sub = df[df["Scenario"] == scen]
        for m_idx, model in enumerate(MODELS):
            means, stds = [], []
            for ds in ds_order:
                row = sub[(sub["Dataset"] == ds) & (sub["Model"] == model)]
                if not row.empty:
                    means.append(float(row["AUC"].iloc[0]))
                    stds.append(float(row["AUC_std"].iloc[0]))
                else:
                    means.append(0.0)
                    stds.append(0.0)
            offset = (m_idx - (len(MODELS) - 1) / 2.0) * width
            is_ours = model == "ArcMDTI"
            bars = ax.bar(
                x + offset,
                means,
                width,
                yerr=stds,
                capsize=2.5,
                label=display_names[model],
                color=palette[model],
                edgecolor="none",
                linewidth=0.0,
                alpha=0.88,
                error_kw=dict(lw=0.9, capthick=0.9, ecolor="#444444"),
                zorder=3,
            )
            if is_ours:
                for bar, val, std in zip(bars, means, stds):
                    if val > 0:
                        ax.text(
                            bar.get_x() + bar.get_width() / 2.0,
                            val + (std if np.isfinite(std) else 0.0) + 0.012,
                            f"{val:.3f}",
                            ha="center",
                            va="bottom",
                            fontsize=7.5,
                            fontweight="bold",
                            color="#C84B3C",
                        )

        ax.set_title(title, fontsize=11.5, fontweight="bold", pad=10)
        ax.set_xticks(x)
        ax.set_xticklabels([DATASET_LABELS[d] for d in ds_order], fontsize=10, fontweight="bold")
        ax.set_ylabel("Area Under ROC Curve (AUC)", fontsize=10.5, fontweight="bold")
        ax.set_ylim(0.42, 0.98)
        ax.grid(axis="y", linestyle="--", alpha=0.45, zorder=0)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="upper center",
        bbox_to_anchor=(0.5, 1.03),
        ncol=5,
        frameon=True,
        facecolor="white",
        edgecolor="#CCCCCC",
        fontsize=9.5,
    )
    plt.tight_layout(rect=[0, 0, 1, 0.92])

    for ext in ("pdf", "png"):
        out_path = OUT_DIR / f"Cold_Start_Comparison.{ext}"
        fig.savefig(out_path, dpi=300, bbox_inches="tight")
        sync_file(out_path)
    plt.close(fig)


def main():
    rows = []
    for dataset in DATASETS:
        for scenario in SCENARIOS:
            for model in MODELS:
                parsed = load_from_result_dir(dataset, scenario, model)
                if parsed is None:
                    log_path = Path(f"result_cold_{model}_{scenario}_{dataset}.log")
                    if log_path.exists():
                        parsed = parse_log(log_path)
                if parsed is None:
                    continue
                rows.append(
                    {
                        "Dataset": dataset,
                        "Scenario": scenario.replace("_", "-"),
                        "Model": model,
                        **parsed,
                    }
                )
    if not rows:
        print("[SKIP] No cold-start results found locally yet.")
        return

    df = pd.DataFrame(rows)
    csv_path = OUT_DIR / "Cold_Start_Baseline_Summary.csv"
    df.to_csv(csv_path, index=False)
    sync_file(csv_path)
    write_cold_start_latex(df)
    plot_cold_start_comparison(df)
    print(f"Aggregated {len(df)} cold-start records -> {csv_path}")


if __name__ == "__main__":
    main()
